def _account(row):
    return replace(account_opened(row['account_id'],row['kind'],row['name'],row['currency'],row['opened_at'],
        institution=row['institution'],account_number=row['account_number'],origin=row['origin'],
        provenance=Provenance(row['issuer_doc_id'])),event_id='cap-account-open:'+row['account_id'])


def _document(row):
    doc = row['doc_id']
    events = []
    def add(event,region):
        events.append(replace(event,event_id=f'cap-event:{doc}:{event.event_type}:{region}'))
    def provenance(item):
        return Provenance(doc,item.get('page'),item.get('region',''))
    add(document_captured(doc,row['filename'],row['byte_count'],row['document_kind'],
                          float(row.get('document_kind_confidence','1')),row['captured_at']),'capture')
    reply = row.get('brokerage_reply') or {
        'currency':next(a['currency'] for a in [*RAW_INPUTS['accounts'],*[v['account'] for v in RAW_INPUTS['variants'].values() if 'account' in v]] if a['account_id']==row['account_id']),
        'opening':{key:row['opening'][key] for key in ('amount_raw','date_raw')},
        'closing':{key:row['closing'][key] for key in ('amount_raw','date_raw')},
        'transactions':[{'date_raw':item['date'],'amount_raw':item['amount_raw'],'description':item['description']} for item in row['transactions']],
    }
    read = row.get('read',{})
    add(read_recorded(doc,read.get('model','synthetic'),read.get('prompt',FIXTURE_VERSION),read.get('mode','text'),
        json.dumps(reply,sort_keys=True),float(read.get('cost','0')),read.get('input_tokens',0),read.get('output_tokens',0),
        read.get('ok',True),read.get('error'),read.get('occurred_at',row['captured_at']),usage_reported=True),'read')
    if 'opening' in row:
        item=row['opening']
        add(opening_balance_observed(row['account_id'],item['amount_raw'],item['date_raw'],provenance(item)),item['region'])
    for item in row['transactions']:
        counter=item['counter_leg']
        postings=[Posting(row['account_id'],item['posted_amount'],item['account_leg_grade']),Posting(counter['account'],counter['amount'],counter['grade'])]
        add(transaction_recorded(postings,item['description'],item['date'],tags=item['tags'],provenance=provenance(item)),item['region'])
    item=row['closing']
    add(closing_balance_observed(row['account_id'],item['amount_raw'],item['date_raw'],provenance(item),confirmed_by=item['confirmed_by']),item['region'])
    for item in row.get('positions',[]):
        add(position_observed(row['account_id'],item['instrument'],item['units_raw'],item['market_value_raw'],item['currency'],item['dated'],
            grade=item['grade'],provenance=Provenance(item['doc_id'],item['page'],item['region'])),item['region'])
    return events


